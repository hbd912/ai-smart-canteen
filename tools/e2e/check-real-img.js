const puppeteer = require('puppeteer-core')
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
;(async () => {
  const b = await puppeteer.launch({ executablePath:'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',
    headless:'new', protocolTimeout:180000, args:['--window-size=1920,1080','--autoplay-policy=no-user-gesture-required','--mute-audio']})
  const p = await b.newPage(); await p.setViewport({width:1920,height:1080})
  const errs=[]; p.on('pageerror', e=>errs.push(String(e).slice(0,200)))
  await p.goto('http://127.0.0.1:5173/', {waitUntil:'networkidle2'})
  await p.waitForSelector('.auth-card', {timeout:45000}); await sleep(500)
  await p.click('#login-username'); await p.type('#login-username','student')
  await p.click('#login-password'); await p.type('#login-password','123456')
  await p.evaluate(()=>document.querySelector('.auth-submit').click())
  await p.waitForFunction(()=>document.querySelector('.scene-view')?.getAttribute('data-scene')==='HOME_IDLE',{timeout:45000})
  await sleep(1500)
  // 进点餐
  await p.evaluate(()=>{
    const el = Array.from(document.querySelectorAll('.sidenav__btn')).find(x=>(x.getAttribute('aria-label')||'')==='点餐')
    for(const t of ['mousedown','mouseup','click']) el.dispatchEvent(new MouseEvent(t,{bubbles:true,cancelable:true}))
  })
  await p.waitForFunction(()=>document.querySelector('.scene-view')?.getAttribute('data-scene')==='MENU_OPEN',{timeout:30000})
  await sleep(1800)
  const imgs = await p.$$eval('.dish-card img', els => els.map(e=>({src:e.getAttribute('src')?.split('/').pop(), w:e.naturalWidth, h:e.naturalHeight, loaded:e.complete&&e.naturalWidth>0})))
  console.log('菜单图片总数:', imgs.length)
  console.log('加载成功:', imgs.filter(i=>i.loaded).length)
  console.log('前6张:', JSON.stringify(imgs.slice(0,6)))
  console.log('pageerror:', errs.length)
  await p.screenshot({path:'shots/real-dishes-menu.png'})
  await b.close()
})()
